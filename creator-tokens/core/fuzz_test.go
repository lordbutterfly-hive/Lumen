// fzOpCandidate.apply returns BOTH an error and an "effect" string. The
// effect matters because several functions in this package can return
// err==nil for two semantically different outcomes — most notably
// RefundHolder, whose own doc explicitly documents a zero-balance call as "a
// harmless no-op: (0, nil)". Grouping permutations by success/fail ALONE
// would conflate "RefundHolder no-op'd because the target was empty at that
// point in the sequence" with "RefundHolder paid out 195" — both succeed,
// but they are NOT the same outcome, and requiring identical final state
// across the two would be a false positive, not a real I6-style violation.
// The effect string (e.g. "payout=0" vs "payout=195") makes the outcome key
// precise enough that only GENUINELY identical outcomes are compared.
type fzOpCandidate struct {
	id    string
	apply func(s *MemStore, block uint64) (effect string, err error)
}

func fzPermutations(n int) [][]int {
	if n == 0 {
		return [][]int{{}}
	}
	var out [][]int
	base := make([]int, n)
	for i := range base {
		base[i] = i
	}
	var perm func(cur, remaining []int)
	perm = func(cur, remaining []int) {
		if len(remaining) == 0 {
			cp := make([]int, len(cur))
			copy(cp, cur)
			out = append(out, cp)
			return
		}
		for i, v := range remaining {
			next := make([]int, 0, len(remaining)-1)
			next = append(next, remaining[:i]...)
			next = append(next, remaining[i+1:]...)
			perm(append(append([]int{}, cur...), v), next)
		}
	}
	perm(nil, base)
	return out
}

// fzBuildOrderingCandidates builds a diverse pool of candidate operations
// against the world `w` as it stands right now, all targeting the SAME
// block. Some are on disjoint creators/holders (trivially commuting), some
// deliberately share a creator (SetFace+SetCap: disjoint fields; two Buys
// on the same curve: NOT additive in price but exactly path-independent in
// total — curve.go L3's telescope, which is precisely what makes them
// order-immune; two RefundHolder pushes for different holders on the SAME
// creator: the genuinely non-trivial case, since each call re-reads the
// PREVAILING reserve/supply ratio), and every currently-pending escrow
// contributes both an Answer and a Reclaim candidate — the direct I6 pair.
func fzBuildOrderingCandidates(rng *rand.Rand, w *fzWorld) []fzOpCandidate {
	var cands []fzOpCandidate
	add := func(id string, apply func(s *MemStore, block uint64) (string, error)) {
		cands = append(cands, fzOpCandidate{id: id, apply: apply})
	}

	for i := 0; i < 3; i++ {
		c := fzCreators[rng.Intn(len(fzCreators))]
		h := fzHolders[rng.Intn(len(fzHolders))]
		n := big.NewInt(int64(1 + rng.Intn(200)))
		id := fmt.Sprintf("buy:%d:%s:%s:%s", i, c, h, n)
		add(id, func(s *MemStore, block uint64) (string, error) {
			res, err := Buy(s, h, c, block, n)
			if err != nil {
				return "", err
			}
			return fmt.Sprintf("due=%v", res.TotalDue), nil
		})
	}

	{
		c := fzCreators[rng.Intn(len(fzCreators))]
		payer := fzHolders[rng.Intn(len(fzHolders))]
		periods := uint64(1 + rng.Intn(3))
		paid := new(big.Int).Mul(big.NewInt(int64(periods)), big.NewInt(SubscriptionFee))
		add(fmt.Sprintf("renew:%s:%s:%d", c, payer, periods), func(s *MemStore, block uint64) (string, error) {
			return "", Renew(s, payer, c, block, periods, paid)
		})
	}

	{
		c := fzCreators[rng.Intn(len(fzCreators))]
		newFace := MinFace + int64(rng.Intn(1000))
		newCap := MinCap + int64(rng.Intn(100000)) + 1
		add(fmt.Sprintf("setface:%s:%d", c, newFace), func(s *MemStore, block uint64) (string, error) {
			return "", SetFace(s, c, c, block, newFace)
		})
		add(fmt.Sprintf("setcap:%s:%d", c, newCap), func(s *MemStore, block uint64) (string, error) {
			return "", SetCap(s, c, c, block, newCap)
		})
	}

	for i := 0; i < 2; i++ {
		c := fzCreators[rng.Intn(len(fzCreators))]
		from := fzHolders[rng.Intn(len(fzHolders))]
		to := fzHolders[rng.Intn(len(fzHolders))]
		if from == to {
			continue
		}
		amt := big.NewInt(int64(1 + rng.Intn(50)))
		id := fmt.Sprintf("xfer:%d:%s:%s:%s:%s", i, c, from, to, amt)
		add(id, func(s *MemStore, block uint64) (string, error) {
			return "", TransferCredits(s, from, c, from, to, block, amt)
		})
	}

	{
		c := fzCreators[rng.Intn(len(fzCreators))]
		h1 := fzHolders[rng.Intn(len(fzHolders))]
		h2 := fzHolders[rng.Intn(len(fzHolders))]
		pusher := fzHolders[rng.Intn(len(fzHolders))]
		if h1 != h2 {
			add(fmt.Sprintf("refundholder:%s:%s", c, h1), func(s *MemStore, block uint64) (string, error) {
				payout, err := RefundHolder(s, pusher, c, h1, block)
				return fmt.Sprintf("payout=%v", payout), err
			})
			add(fmt.Sprintf("refundholder:%s:%s", c, h2), func(s *MemStore, block uint64) (string, error) {
				payout, err := RefundHolder(s, pusher, c, h2, block)
				return fmt.Sprintf("payout=%v", payout), err
			})
		}
	}

	for _, ref := range w.pendingEscrows {
		ref := ref
		add(fmt.Sprintf("answer:%s:%d", ref.creator, ref.seq), func(s *MemStore, block uint64) (string, error) {
			res, err := Answer(s, ref.creator, ref.creator, block, ref.seq, "ans")
			return fmt.Sprintf("res=%+v", res), err
		})
		add(fmt.Sprintf("reclaim:%s:%d", ref.creator, ref.seq), func(s *MemStore, block uint64) (string, error) {
			res, err := Reclaim(s, ref.asker, ref.creator, block, ref.seq)
			return fmt.Sprintf("res=%+v", res), err
		})
	}

	return cands
}

func TestFuzzOrderingImmunity(t *testing.T) {
	const seed = int64(20260720003)
	const trials = 800
	rng := rand.New(rand.NewSource(seed))
	tr := &fzTrace{seed: seed}

	for trial := 0; trial < trials; trial++ {
		w := fzNewWorld()
		w.block = 1
		setupSteps := 20 + rng.Intn(60)
		for i := 0; i < setupSteps; i++ {
			fzApplyRandomAction(t, rng, w, tr)
		}
		block := w.block // the shared "given block" every candidate is tried at

		candidates := fzBuildOrderingCandidates(rng, w)
		if len(candidates) < 2 {
			continue
		}

		// Legality filter: keep only candidates individually legal against a
		// FRESH copy of the common starting snapshot.
		var legal []fzOpCandidate
		legalByID := map[string]bool{}
		for _, cand := range candidates {
			clone := fzCloneStore(w.s)
			if _, err := cand.apply(clone, block); err == nil {
				legal = append(legal, cand)
				legalByID[cand.id] = true
			}
		}

		// Direct I6 generalisation: an Answer and a Reclaim for the SAME
		// escrow must never BOTH be individually legal at the same block.
		for _, ref := range w.pendingEscrows {
			aID := fmt.Sprintf("answer:%s:%d", ref.creator, ref.seq)
			rID := fmt.Sprintf("reclaim:%s:%d", ref.creator, ref.seq)
			if legalByID[aID] && legalByID[rID] {
				tr.dump(t, 200)
				t.Fatalf("trial %d: I6 VIOLATED: both %s and %s are individually legal at block %d", trial, aID, rID, block)
			}
		}

		if len(legal) < 2 {
			continue
		}
		n := len(legal)
		if n > 4 {
			n = 4
		}
		idxs := rng.Perm(len(legal))[:n]
		subset := make([]fzOpCandidate, n)
		subsetIDs := make([]string, n)
		for i, idx := range idxs {
			subset[i] = legal[idx]
			subsetIDs[i] = legal[idx].id
		}

		type permResult struct {
			outcomeKey string
			dump       string
		}
		byOutcome := map[string][]permResult{}

		for _, perm := range fzPermutations(n) {
			clone := fzCloneStore(w.s)
			var succeeded []string
			for _, pidx := range perm {
				op := subset[pidx]
				effect, err := op.apply(clone, block)
				if err == nil {
					// Include the EFFECT, not just the id: a RefundHolder
					// that no-op'd (payout=0) and one that paid out real
					// value are different outcomes even though both return
					// err==nil (RefundHolder's own doc: a zero balance is "a
					// harmless no-op: (0, nil)") — conflating them would
					// compare permutations that did genuinely different
					// things and call any difference a false "violation".
					succeeded = append(succeeded, op.id+"["+effect+"]")
				}
			}
			sort.Strings(succeeded)
			outcomeKey := strings.Join(succeeded, ",")
			// Order-invariant money state + the two aggregates whose
			// per-key distribution is order-dependent by design (see
			// fzOrderInvariantDump for the full justification).
			dump := fzOrderInvariantDump(clone) + "\n" + fzOrderAggregates(clone)
			byOutcome[outcomeKey] = append(byOutcome[outcomeKey], permResult{outcomeKey: outcomeKey, dump: dump})

			// Whatever DID succeed in this permutation must still leave the
			// system internally consistent — catches accounting corruption
			// even in the documented "order-dependent success" case.
			fzCheckInvariantsOnStore(t, clone, tr, fmt.Sprintf("trial %d perm %v", trial, perm), fzEscrowedSnapshot(clone))
		}

		for outcome, group := range byOutcome {
			first := group[0].dump
			for gi := 1; gi < len(group); gi++ {
				if group[gi].dump != first {
					tr.dump(t, 200)
					t.Fatalf("trial %d: ORDERING NOT IMMUNE: op set %v — the SAME ops succeeded (%s) in every order, but final state differs by permutation.\n--- state A ---\n%s\n--- state B ---\n%s",
						trial, subsetIDs, outcome, first, group[gi].dump)
				}
			}
		}
		if len(byOutcome) > 1 {
			var keys []string
			for k := range byOutcome {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			tr.add("trial %d: op set %v has ORDER-DEPENDENT SUCCESS (documented, intended: resource contention, not an I6 violation) — outcome groups: %v", trial, subsetIDs, keys)
		}
	}
	t.Logf("TestFuzzOrderingImmunity: %d trials passed (seed=%d), subsets up to size 4 (<=24 permutations each)", trials, seed)
}

