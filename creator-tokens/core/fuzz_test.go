// fuzz_test.go — randomized property suite over the WHOLE core contract
// surface (API.md): register/renew/buy/sell/claimTradeFees/ask/answer/
// reclaim/transfer/refund/refundHolder/setFace/setCap/closeIfDrained/
// recordObs/askRate, across several markets and holders, with random
// amounts and random block advances.
//
// PORTED OFF THE PAR MINT (2026-07-21, this rewrite): the issuance path is
// Buy on the curve — Prepay is DELETED with its mechanism (an unbounded
// mint-cheap/redeem-dear loop against the curve; transfer.go's header has
// the autopsy) — and the suite's old load-bearing invariant, the PAR PEG
// (reserve == supply exactly), is replaced by the CURVE invariant below.
// Sell and ClaimTradeFees join the action mix; TransferCredits carries its
// RULING-A `block` parameter.
//
// OWNERSHIP: this file only. Every helper below is prefixed `fz` — five
// other authors already have helpers in this package (setupMarket,
// sumBalances, errSymbol, forceFrozen, activateMarket, mustRegister, ...)
// and nothing here may collide with any of them.
//
// DECORRELATION: the scripted end-to-end harness (harness_test.go) follows
// storylines; nothing here does — every sequence is generated by math/rand
// from a fixed seed, every parameter choice is adversarial (boundary-
// biased, not "plausible"), and failures print the seed plus the full step
// trace so they are exactly replayable.
//
// -----------------------------------------------------------------------
// THE CURVE INVARIANT (replaces the PAR peg — read before the checks).
//
// Through the public API alone, for every creator:
//
//	reserve(c) >= area(supply(c))  ALWAYS, and
//	reserve(c) == area(supply(c))  EXACTLY until the market's first
//	                               wind-down refund of its current
//	                               incarnation.
//
// Why the equality (RULING A/I): Buy adds exactly the area step
// area(S+n) − area(S); Sell removes exactly area(S) − area(S−ΔS); no other
// function touches kReserve; induction from the S=0, R=0 genesis.
//
// Why wind-down flips it to >=: Refund/RefundHolder pay the flat pro-rata
// floor(R·c/S), which is <= the marginal area step the burn un-backs
// (average <= marginal on a rising curve), so each refund leaves
// R' >= area(S') — the floor dust flows FORWARD to later claimants
// (refund.go C-22), never out. Buys are structurally dead in FROZEN/CLOSED
// (RequireInflowOpen), so the surplus is not buyable — and C-24 proves the
// LAST refund drains R to exactly 0, so a re-registered incarnation starts
// back at equality. The walk tracks "has this incarnation refunded yet"
// per creator and asserts the equality form whenever it can.
//
// Rounding property #4 under the curve: the ONE rounding site is area's
// floor (curve.go); trade totals are exact area steps (equalities L1-L5,
// asserted per-op in curve_fuzz_test.go); refund rounding favours the
// remaining holders (C-22). The places rounding is genuinely live remain
// credits-per-ask (ceilDiv(face,rate)) and twap.go's floor — both fuzzed
// independently below, unchanged.
// ===========================================================================

